"""Project-scoped, connection-owned stdio MCP adapter. Python 3.9+, stdlib only.

Only code imports are reused. Both protected files and all active policy are read fresh; no polling or daemon.
"""
import json
import os
from pathlib import Path
import re
import sys

REQUEST_LIMIT = 262144
RESPONSE_LIMIT = 65536
PROTOCOL_VERSION = "2025-06-18"  # supported stdio tools/text schema; unknown versions negotiate this fallback
TOOL = "factory_hook"
CATALOG = [{"name": TOOL, "description": "Evaluate one scoped factory lifecycle event against fresh local state.",
            "inputSchema": {"type": "object", "properties": {"event": {"type": "object"}},
                            "required": ["event"], "additionalProperties": False},
            "_meta": {"ui": {"visibility": []}}}]


def serve(scope, reader=None, writer=None):
    """One bounded serial connection; no child process or request queue. EOF always exits."""
    if not re.fullmatch(r"[0-9a-f]{16}", scope):
        raise SystemExit("Use the scope generated by project hook setup")
    reader = reader or sys.stdin.buffer
    writer = writer or sys.stdout.buffer
    home = Path(os.environ.get("SAFE_ENGINE_HOME") or Path.home() / ".safe-engine")
    sources = (home / "active" / (scope + ".json"), home / "runs" / (scope + ".json"))
    gate = None

    def diagnostic(status, error=None):
        # Import the shared bounded logger only for a real failure/active policy, never an idle callback.
        nonlocal gate
        try:
            if gate is None:
                import fast_gate
                gate = fast_gate
            gate.log("hook.server", status=status, **({"error_class": type(error).__name__} if error else {}))
        except Exception:
            pass

    def answer(method, params):
        nonlocal gate
        if method == "initialize":
            version = params.get("protocolVersion")
            if not isinstance(version, str) or len(version) > 32:
                raise ValueError("Invalid protocol version")
            diagnostic("initialized")
            return {"protocolVersion": PROTOCOL_VERSION, "capabilities": {"tools": {}},
                    "serverInfo": {"name": "safe-engine-project-hooks", "version": "1"}}
        if method == "ping":
            return {}
        if method == "tools/list":
            return {"tools": CATALOG}
        if method != "tools/call" or params.get("name") != TOOL:
            raise LookupError("Unsupported method or tool")
        args = params.get("arguments", {})
        if not isinstance(args, dict) or set(args) != {"event"} or not isinstance(args["event"], dict):
            raise ValueError("Invalid hook event")
        output = {}
        if any(path.is_file() for path in sources):
            if gate is None:
                import fast_gate
                gate = fast_gate
            text, _code = gate.hook_answer(args["event"], "codex", scope)
            if text:
                output = json.loads(text)
        # Codex's hook executor consumes text blocks, not structuredContent.
        return {"content": [{"type": "text", "text": json.dumps(output, ensure_ascii=False)}], "isError": False}

    while True:
        line = reader.readline(REQUEST_LIMIT + 1)
        if not line:
            return 0
        request_id = None
        try:
            if len(line) > REQUEST_LIMIT:
                while line and not line.endswith(b"\n"):
                    line = reader.readline(65536)
                raise ValueError("Request limit")
            request = json.loads(line.decode("utf-8"))
            if not isinstance(request, dict) or request.get("jsonrpc") != "2.0":
                raise ValueError("Invalid request")
            request_id = request.get("id")
            if "id" not in request:  # initialized/cancel notifications need no reply or side effect
                continue
            if isinstance(request_id, bool) or not isinstance(request_id, (str, int)) or len(str(request_id)) > 128:
                request_id = None
                raise ValueError("Invalid request ID")
            params = request.get("params", {})
            if not isinstance(params, dict):
                raise ValueError("Invalid params")
            response = {"jsonrpc": "2.0", "id": request_id, "result": answer(request.get("method"), params)}
            encoded = json.dumps(response, ensure_ascii=False).encode("utf-8") + b"\n"
            if len(encoded) > RESPONSE_LIMIT:
                raise ValueError("Response limit")
        except Exception as error:
            diagnostic("request_failed", error)
            response = {"jsonrpc": "2.0", "id": request_id,
                        "error": {"code": -32601 if isinstance(error, LookupError) else -32602,
                                  "message": "Factory hook request failed; inspect the private gate log and reconnect after repair"}}
            encoded = json.dumps(response).encode("utf-8") + b"\n"
        try:
            writer.write(encoded)
            writer.flush()
        except (OSError, ValueError):  # disconnected owner: exit; logging never traps shutdown
            return 0


def main():
    if sys.version_info < (3, 9):
        raise SystemExit("Project hooks need Python 3.9+")
    if len(sys.argv) != 2:
        raise SystemExit("Use project hook setup to configure this adapter")
    sys.pycache_prefix = str(Path(os.environ.get("SAFE_ENGINE_HOME") or Path.home() / ".safe-engine") / "pycache")
    return serve(sys.argv[1])


if __name__ == "__main__":
    sys.exit(main())
